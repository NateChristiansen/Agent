FEATURES_BASE_YAML = """\
# GENERATED by `agent status render` — do not edit. Views over features/*/plan.md frontmatter.
filters:
  and:
    - file.hasTag("feature")
    - 'file.name == "plan"'

formulas:
  # `opened` is written unquoted (opened: 2026-09-15), so Obsidian hands Bases a date object
  # already. date() takes a string and errors on an object ("Type error in date, parameter
  # input. Expected String, given Object"), so the property is read directly.
  age_days: 'if(opened, (today() - opened).days, "")'
  # opened is a date without a time, so relative() would count from midnight; show the
  # date and whole days instead.
  open_since: 'if(closed, "", if(opened, opened.format("YYYY-MM-DD") + " (" + (today() - opened).days + "d)", ""))'
  # The card title on the Board. A card's heading is its first ordered property, and with the
  # plain title there the number was nowhere on the tile. The number leads so it survives the heading's truncation. Zero-padded by
  # hand: Bases has no padStart, and `slice` on a built-up string is harder to read than this.
  numbered: 'if(id, if(id < 10, "00", if(id < 100, "0", "")) + id.toString() + " · " + title, title)'

properties:
  note.id:
    displayName: "#"
  note.title:
    displayName: Title
  note.status:
    displayName: Status
  note.repos:
    displayName: Repos
  note.tickets:
    displayName: Tickets
  note.opened:
    displayName: Opened
  note.closed:
    displayName: Closed
  note.adrs:
    displayName: ADRs
  note.links:
    displayName: Links
  formula.age_days:
    displayName: Age (days)
  formula.open_since:
    displayName: Open since
  formula.numbered:
    displayName: Feature

views:
  - type: table
    name: Open
    filters:
      and:
        - 'status != "done"'
        - 'status != "abandoned"'
    order:
      - note.id
      - note.title
      - note.status
      - note.repos
      - note.tickets
      - formula.age_days
    sort:
      - property: note.status
        direction: ASC
      - property: note.id
        direction: ASC

  - type: cards
    name: Board
    filters:
      and:
        - 'status != "done"'
        - 'status != "abandoned"'
    groupBy:
      property: note.status
      direction: ASC
    order:
      - formula.numbered
      - note.repos
      - formula.open_since
      - note.links

  - type: table
    name: Closed
    filters:
      or:
        - 'status == "done"'
        - 'status == "abandoned"'
    order:
      - note.id
      - note.title
      - note.status
      - note.opened
      - note.closed
    sort:
      - property: note.closed
        direction: DESC

  - type: table
    name: All
    order:
      - note.id
      - note.title
      - note.status
      - note.repos
      - note.tickets
      - note.opened
      - note.closed
      - note.adrs
    sort:
      - property: note.id
        direction: ASC
"""

