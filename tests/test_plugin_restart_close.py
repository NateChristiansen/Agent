"""An Obsidian restart brought back every manager tab and started a fresh agent in each. The owner
wants a fresh start with no session resumed (2026-09-30): agent-terminal-focus
closes the ribbon's manager tabs once the restored layout is ready, only at app start, and
leaves every other tab alone."""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

PLUGIN = Path(__file__).resolve().parents[1] / "harness/obsidian/plugins/agent-terminal-focus/main.js"
UUID = "0f8e2c4a-1b2c-4d3e-8f90-123456789abc"

# Loads the plugin with a restored layout of named leaves; `ready` says whether the layout was
# already ready at load (a plugin enabled mid-session). Prints which leaves were detached.
HARNESS = r"""
const Module = require('module');
const [pluginPath, platform, ready, payload] = process.argv.slice(1);
Object.defineProperty(process, 'platform', {value: platform});
class Plugin {
  constructor(app) { this.app = app; }
  addRibbonIcon() {} registerEvent() {} registerDomEvent() {} register() {} registerInterval() {}
  registerObsidianProtocolHandler() {}
}
const load = Module._load;
Module._load = function (request, ...rest) {
  if (request === 'obsidian') return {addIcon() {}, Modal: class {}, Notice: class {}, Plugin};
  if (request === 'child_process') return {execFile(cmd, args, opts, cb) { setImmediate(() => cb(null, '[]', '')); return {pid: 1}; }};
  return load.call(this, request, ...rest);
};
globalThis.window = {setInterval() { return 1; }};
globalThis.document = {};
const Klass = require(pluginPath);
// {"ribbon": [os, client]} is the profile the plugin's own ribbon writes on that OS
const generated = ([os, client]) => {
  Object.defineProperty(process, 'platform', {value: os});
  const profile = Klass.managerProfile(client, `${client}:0f8e2c4a-1b2c-4d3e-8f90-123456789abc`, '/vault');
  Object.defineProperty(process, 'platform', {value: platform});
  return {type: 'terminal:terminal', state: {'terminal:terminal': {profile}}};
};
const detached = [];
const leaves = JSON.parse(payload).map(({name, state}) => {
  const view = state && state.ribbon ? generated(state.ribbon) : state;
  return {
    name,
    getViewState() { if (view === 'throws') throw new Error('deferred'); return view; },
    detach() { detached.push(name); },
  };
});
const readyCallbacks = [];
const app = {workspace: {
  layoutReady: ready === 'yes',
  getLeavesOfType: (type) => (type === 'terminal:terminal' ? leaves : []),
  onLayoutReady(fn) { readyCallbacks.push(fn); },
  on() { return {}; },
}, vault: {adapter: {getBasePath: () => '/vault'}}};
new Klass(app).onload();
readyCallbacks.forEach((fn) => fn());
setTimeout(() => console.log(JSON.stringify({detached})), 20);
"""


def _terminal(executable: str, args: list[str]) -> dict:
    profile = {"executable": executable, "args": args}
    return {"type": "terminal:terminal", "state": {"terminal:terminal": {"profile": profile}}}


WIN_COMMAND = f"$env:AGENT_RIBBON_LAUNCH='codex:{UUID}'; codex"
ZSH_COMMAND = f"AGENT_RIBBON_LAUNCH=claude:{UUID} claude; exec /bin/zsh --login"

LEAVES = [
    # the profiles the ribbon itself writes, generated by the plugin
    {"name": "codex-win", "state": {"ribbon": ["win32", "codex"]}},
    {"name": "claude-mac", "state": {"ribbon": ["darwin", "claude"]}},
    {"name": "codex-linux", "state": {"ribbon": ["linux", "codex"]}},
    # the owner's own terminals, including ones that merely contain a valid marker
    {"name": "plain-shell", "state": _terminal("/bin/zsh", ["--login"])},
    {"name": "no-args", "state": {"type": "terminal:terminal", "state": {}}},
    {
        "name": "embedded-win",
        "state": _terminal("powershell.exe", ["-NoLogo", "-NoExit", "-Command", "echo " + WIN_COMMAND]),
    },
    {"name": "embedded-zsh", "state": _terminal("/bin/zsh", ["-i", "--login", "-c", "echo " + ZSH_COMMAND])},
    {
        "name": "extra-command",
        "state": _terminal("/bin/zsh", ["-i", "--login", "-c", ZSH_COMMAND + "; rm x"]),
    },
    {
        "name": "client-mismatch",
        "state": _terminal(
            "powershell.exe", ["-NoLogo", "-NoExit", "-Command", WIN_COMMAND.replace("; codex", "; claude")]
        ),
    },
    {"name": "wrong-shell", "state": _terminal("/bin/sh", ["-i", "--login", "-c", ZSH_COMMAND])},
    {
        "name": "extra-arg",
        "state": _terminal("powershell.exe", ["-NoLogo", "-NoExit", "-Command", WIN_COMMAND, "x"]),
    },
    {"name": "note", "state": {"type": "markdown", "state": {"file": "Dashboard.md"}}},
    {"name": "throws", "state": "throws"},
]


def _run(platform: str, ready: str) -> list[str]:
    if shutil.which("node") is None:
        pytest.skip("node is not installed")
    proc = subprocess.run(
        ["node", "-e", HARNESS, str(PLUGIN), platform, ready, json.dumps(LEAVES)],
        capture_output=True,
        text=True,
        check=True,
        timeout=30,
    )
    return json.loads(proc.stdout.strip().splitlines()[-1])["detached"]


@pytest.mark.parametrize("platform", ["darwin", "win32"])
def test_restored_manager_tabs_close_at_app_start(platform: str):
    assert _run(platform, "no") == ["codex-win", "claude-mac", "codex-linux"]


def test_a_plugin_enabled_mid_session_leaves_live_managers_alone():
    assert _run("darwin", "yes") == []
